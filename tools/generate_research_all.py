#!/usr/bin/env python3
"""Build hoimod_research_all from the installed Hearts of Iron IV technology files."""

from __future__ import annotations

import re
import sys
from pathlib import Path

GAME_TECH_DIR = Path(
    "/home/vinoc/.local/share/Steam/steamapps/common/Hearts of Iron IV/common/technologies"
)
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "common/scripted_effects/hoimod_research_all.txt"
TECH_OUT = ROOT / "common/technologies"
CHUNK = 40
XOR_LINE = re.compile(r"\bxor\s*=\s*\{", re.IGNORECASE)

IDENT = re.compile(r"^(\s*)([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{")
NESTED = {
    "folder",
    "path",
    "ai_will_do",
    "enable_equipments",
    "enable_equipment_modules",
    "enable_subunits",
    "categories",
    "xor",
    "modifier",
    "dependencies",
    "on_research_complete",
    "allow",
    "allow_branch",
    "sub_technologies",
    "enable_building",
    "research_cost_coeff",
}


def strip_comments(text: str) -> str:
    return "\n".join(line.split("#", 1)[0] for line in text.splitlines())


def collect_techs(tech_dir: Path) -> list[str]:
    found: list[str] = []
    seen: set[str] = set()
    for path in sorted(tech_dir.glob("*.txt")):
        depth = 0
        for line in strip_comments(path.read_text(encoding="utf-8-sig")).splitlines():
            match = IDENT.match(line)
            if match and depth == 1:
                tech_id = match.group(2)
                if tech_id.lower() in NESTED:
                    raise SystemExit(f"{path.name}: nested key extracted as a technology: {tech_id}")
                if tech_id not in seen:
                    seen.add(tech_id)
                    found.append(tech_id)
            depth += line.count("{") - line.count("}")
        if depth != 0:
            raise SystemExit(f"{path.name}: unbalanced braces ({depth})")
    return found


def strip_xor(text: str) -> tuple[str, int]:
    """Drop xor/XOR blocks so exclusive branches can all stay researched."""
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    removed = 0
    index = 0
    while index < len(lines):
        code = lines[index].split("#", 1)[0]
        if XOR_LINE.search(code):
            depth = code.count("{") - code.count("}")
            index += 1
            while depth > 0 and index < len(lines):
                depth += lines[index].split("#", 1)[0].count("{") - lines[index].split("#", 1)[0].count("}")
                index += 1
            removed += 1
            continue
        out.append(lines[index])
        index += 1
    return "".join(out), removed


def write_tech_overrides(tech_dir: Path) -> int:
    TECH_OUT.mkdir(parents=True, exist_ok=True)
    removed = 0
    for path in sorted(tech_dir.glob("*.txt")):
        stripped, count = strip_xor(path.read_text(encoding="utf-8-sig"))
        body = "\n".join(line.split("#", 1)[0] for line in stripped.splitlines())
        depth = 0
        for line in body.splitlines():
            depth += line.count("{") - line.count("}")
            if depth < 0:
                raise SystemExit(f"{path.name}: xor strip broke braces")
        if depth != 0:
            raise SystemExit(f"{path.name}: xor strip left depth {depth}")
        if XOR_LINE.search(body):
            raise SystemExit(f"{path.name}: xor block survived")
        header = "# hoimod1: XOR removed so every branch can stay researched. Generated.\n"
        (TECH_OUT / path.name).write_text(header + stripped, encoding="utf-8")
        removed += count
    return removed


def main() -> None:
    tech_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else GAME_TECH_DIR
    techs = collect_techs(tech_dir)
    if len(techs) < 100:
        raise SystemExit(f"only {len(techs)} technologies found; parser is probably wrong")
    removed = write_tech_overrides(tech_dir)
    ordered = sorted(techs)
    chunks = [ordered[index : index + CHUNK] for index in range(0, len(ordered), CHUNK)]
    lines = [
        "# Generated by tools/generate_research_all.py. Do not edit by hand.",
        "",
    ]
    for number, chunk in enumerate(chunks):
        lines.append(f"hoimod_research_all_{number} = {{")
        lines.append("\tset_technology = {")
        lines.append("\t\tpopup = no")
        lines.extend(f"\t\t{tech_id} = 1" for tech_id in chunk)
        lines.append("\t}")
        lines.append("}")
        lines.append("")
    lines.append("hoimod_research_all = {")
    lines.extend(f"\thoimod_research_all_{number} = yes" for number in range(len(chunks)))
    lines.append("}")
    lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(techs)} technologies in {len(chunks)} chunks to {OUTPUT}")
    print(f"removed {removed} XOR blocks into {TECH_OUT}")


if __name__ == "__main__":
    main()
